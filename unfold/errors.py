"""unfold が投げる例外。"""


class UnfoldError(Exception):
    """設定の誤りなど、利用者が直せる問題。

    メッセージには**次に何をすればよいか**まで書くこと。
    特に教師ラベルまわりは仕様書の前提（200件の正解がある）が
    中古車データでは成り立たないので、ここで黙って推測しない。
    """


class UnfoldWarning(UserWarning):
    """止めるほどではないが、黙って進むと結果を読み違える問題。

    重複レコードの検知（`unfold.leakage`）がこれを使う。**例外にしないのは、
    重複が意図的なこともあるうえ、止めると「とりあえず動かす」ができなく
    なるため。**気づけることが目的で、`check_leakage=False` で切れる。
    """
